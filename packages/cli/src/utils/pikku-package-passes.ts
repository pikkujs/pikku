import {
  runPikkuAllChild,
  resolvePikkuBin,
} from '../deploy/codegen/per-unit-codegen.js'

/**
 * A pass over a listed package is its own `pikku all`, run from its directory.
 * The environment flag tells it that a root project asked for the run: the
 * package needs no `backends` or `frontends` of its own, and builds none.
 */
export const PACKAGE_PASS_ENV = 'PIKKU_PACKAGE_PASS'

export type ListedPackage = {
  entry: string
  dir: string
  name: string
  namespace: string
}

export class PikkuPackagePassError extends Error {
  constructor(
    readonly entry: string,
    readonly exitCode: number | string | undefined,
    output: string
  ) {
    super(
      `pikku all failed in ${entry} (exit code ${exitCode ?? 'unknown'}).${output ? `\n${output}` : ''}`
    )
    this.name = 'PikkuPackagePassError'
  }
}

/**
 * Run `pikku all` in each listed package, one after the other in the order
 * given (dependencies first), and stop at the first that fails with that
 * package's exit code and output.
 */
export const runPikkuPackagePasses = async (
  packages: ListedPackage[],
  onPass?: (pkg: ListedPackage) => void
): Promise<void> => {
  const pikkuBin = resolvePikkuBin()
  for (const pkg of packages) {
    onPass?.(pkg)
    try {
      await runPikkuAllChild(pikkuBin, pkg.dir, [], {
        deployCodegen: false,
        timeoutMs: 0,
        env: { [PACKAGE_PASS_ENV]: '1' },
      })
    } catch (error) {
      const failure = error as {
        code?: number | string
        stdout?: string
        stderr?: string
      }
      throw new PikkuPackagePassError(
        pkg.entry,
        failure.code,
        [failure.stdout, failure.stderr].filter(Boolean).join('\n').trim()
      )
    }
  }
}

/**
 * The wiring that makes each listed package a wired addon of the root project:
 * its functions are read from the package's own generated metadata, the way a
 * host reads any installed addon. `expose` follows each function's own
 * `expose: true`.
 */
export const serializePikkuPackages = (packages: ListedPackage[]): string => {
  const wirings = packages
    .map(
      (pkg) =>
        `wireAddon({ name: '${pkg.namespace}', package: '${pkg.name}', expose: true })`
    )
    .join('\n')
  return `/* Generated by pikku from pikkuDirectories. Do not edit. */
import { wireAddon } from '#pikku/addon'

${wirings}
`
}
