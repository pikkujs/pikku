#!/usr/bin/env bun
/**
 * Refreshes src/contract/ from the published cloud API contract.
 *
 *   bun run sync-contract                 latest @pikkustudio/addon-cloud-api
 *   bun run sync-contract -- --range 0.0.2
 *   bun run sync-contract -- --tarball ./pikkustudio-addon-cloud-api-0.0.3.sdk.tgz
 *   bun run sync-contract -- --registry http://localhost:4000
 *
 * The registry is the one `wireRemoteAddon` packages resolve against:
 * `POST /rpc/registry:resolveSdk` answers the highest version satisfying the
 * range, its sha512 integrity and a short-lived signed URL. Reading is public,
 * so no credential is sent or needed. The download is verified against the
 * integrity before anything is written.
 *
 * Writes:
 *   src/contract/cloud-api-types.ts       the rpc map types (bare function names)
 *   src/contract/cloud-api-meta.ts  package, version, contractHash, integrity
 *                                       and the list of function names
 */
import { createHash } from 'node:crypto'
import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PACKAGE = '@pikkustudio/addon-cloud-api'
/** `wireAddon({ name: 'cloud', package: '@pikkustudio/addon-cloud-api' })` in the controlplane's cloud-api.wiring.ts */
const NAMESPACE = 'cloud'
const MAP_ENTRY = 'rpc/pikku-rpc-wirings-map.remote.gen.d.ts'
const META_ENTRY = 'function/pikku-functions-meta.gen.json'
const MAP_CUT = '// No addon packages, use RPCMap directly'

const outDir = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/contract'
)

function arg(name: string): string | undefined {
  const i = process.argv.indexOf(`--${name}`)
  return i === -1 ? undefined : process.argv[i + 1]
}

const sha512 = (data: Buffer) =>
  `sha512-${createHash('sha512').update(data).digest('base64')}`

function entry(tarball: string, path: string): string {
  const r = spawnSync('tar', ['-xzOf', tarball, path], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  })
  if (r.status !== 0) throw new Error(`${tarball} has no ${path}`)
  return r.stdout
}

async function obtain(): Promise<{ file: string; integrity: string }> {
  const local = arg('tarball')
  if (local) {
    return { file: resolve(local), integrity: sha512(readFileSync(local)) }
  }
  const registry = (arg('registry') ?? 'https://api.pikkustudio.app').replace(
    /\/$/,
    ''
  )
  const range = arg('range') ?? '*'
  const res = await fetch(`${registry}/rpc/registry:resolveSdk`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      rpcName: 'registry:resolveSdk',
      data: { name: PACKAGE, range },
    }),
  })
  if (!res.ok)
    throw new Error(`resolveSdk ${PACKAGE}@${range}: HTTP ${res.status}`)
  const { url, integrity } = (await res.json()) as {
    url: string
    integrity: string
  }
  const dl = await fetch(url)
  if (!dl.ok) throw new Error(`download failed: HTTP ${dl.status}`)
  const bytes = Buffer.from(await dl.arrayBuffer())
  if (sha512(bytes) !== integrity)
    throw new Error('downloaded SDK does not match the registry integrity')
  const file = join(mkdtempSync(join(tmpdir(), 'cloud-api-sdk-')), 'sdk.tgz')
  writeFileSync(file, bytes)
  return { file, integrity }
}

const { file, integrity } = await obtain()
const manifest = JSON.parse(entry(file, 'manifest.json')) as {
  name: string
  version: string
  contractHash: string
}
if (manifest.name !== PACKAGE)
  throw new Error(`expected ${PACKAGE}, got ${manifest.name}`)

const map = entry(file, MAP_ENTRY)
const cut = map.indexOf(MAP_CUT)
if (cut === -1)
  throw new Error(
    `${MAP_ENTRY} has no "${MAP_CUT}" marker; the SDK layout changed`
  )
const types =
  map.slice(0, cut).trimEnd() + '\n\nexport type FlattenedRPCMap = RPCMap\n'

const meta = JSON.parse(entry(file, META_ENTRY)) as Record<
  string,
  { remote?: boolean }
>
const names = Object.keys(meta)
  .filter((n) => meta[n]!.remote)
  .sort()
const mapKeys = [...types.matchAll(/^ {2}readonly '([^']+)': RPCHandler</gm)]
  .map((m) => m[1]!)
  .sort()
if (JSON.stringify(names) !== JSON.stringify(mapKeys))
  throw new Error('the contract meta and the rpc map list different functions')

const banner = `// Generated by scripts/sync-contract.ts from ${PACKAGE}@${manifest.version}. Do not edit.\n`
mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'cloud-api-types.ts'), `${banner}${types}`)
writeFileSync(
  join(outDir, 'cloud-api-meta.ts'),
  `${banner}
/** The addon name production serves the contract under: \`/rpc/<namespace>:<function>\`. */
export const CLOUD_NAMESPACE = ${JSON.stringify(NAMESPACE)}

export const CLOUD_CONTRACT = {
  package: ${JSON.stringify(PACKAGE)},
  version: ${JSON.stringify(manifest.version)},
  contractHash: ${JSON.stringify(manifest.contractHash)},
  integrity: ${JSON.stringify(integrity)},
} as const

/** Every function the contract carries, by its bare name. */
export const CLOUD_CONTRACT_RPCS: ReadonlySet<string> = new Set(${JSON.stringify(names, null, 2)})
`
)
console.log(
  `${PACKAGE}@${manifest.version} (${names.length} functions) -> src/contract/`
)
