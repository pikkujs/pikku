// Vendors the built cloudsupport data into src/cloudsupport.data.ts.
//
//   cd ../cloudsupport && npm run build
//   node scripts/sync-cloudsupport.mjs ../cloudsupport/dist/cloudsupport.json
//
// The data is a snapshot committed with the CLI, so a deploy plan is the same
// for everyone on a given release and never needs the network.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const source = process.argv[2]
if (!source) {
  console.error(
    'usage: node scripts/sync-cloudsupport.mjs <path to cloudsupport.json>'
  )
  process.exit(1)
}
const data = JSON.parse(readFileSync(source, 'utf8'))
if (data.schemaVersion !== 1) {
  console.error(
    `unsupported schemaVersion ${data.schemaVersion}; this script reads 1`
  )
  process.exit(1)
}
const out = fileURLToPath(
  new URL('../src/cloudsupport.data.ts', import.meta.url)
)
writeFileSync(
  out,
  `// Generated by scripts/sync-cloudsupport.mjs from pikkujs/cloudsupport. Do not edit.
import type { CloudSupportData } from './cloudsupport.js'

export const CLOUDSUPPORT: CloudSupportData = ${JSON.stringify(data, null, 2)}
`
)
console.log(`✔ ${Object.keys(data.packages).length} packages -> ${out}`)
