import { copyFile, mkdir, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { extname, join, resolve } from 'node:path'

export const EMBEDDED_DIR_NAME = 'embedded'
export const EMBEDDED_MANIFEST_FILE = 'embedded-files.gen.js'

export const embeddedEnvName = (name: string) =>
  `PIKKU_EMBEDDED_${name.toUpperCase().replace(/[^A-Z0-9]/g, '_')}`

export async function stageEmbeddedFiles(
  projectDir: string,
  unitDir: string,
  embed: Record<string, string> | undefined
): Promise<string[]> {
  const target = join(unitDir, EMBEDDED_DIR_NAME)
  await rm(target, { recursive: true, force: true })
  await rm(join(unitDir, EMBEDDED_MANIFEST_FILE), { force: true })
  const entries = Object.entries(embed ?? {})
  if (entries.length === 0) return []

  await mkdir(target, { recursive: true })
  const lines = ['// Generated by @pikku/cli — do not edit']
  const exports: string[] = []
  for (const [index, [name, path]] of entries.entries()) {
    const source = resolve(projectDir, path)
    if (!existsSync(source)) {
      throw new Error(
        `deploy.embed.${name} points at ${path}, which does not exist. Build it before deploying.`
      )
    }
    const file = `${name}${extname(source)}`
    await copyFile(source, join(target, file))
    lines.push(
      `import embedded${index} from './${EMBEDDED_DIR_NAME}/${file}' with { type: 'file' }`
    )
    exports.push(`  { env: '${embeddedEnvName(name)}', path: embedded${index} },`)
  }
  lines.push('', 'export const embeddedFiles = [', ...exports, ']', '')
  await writeFile(join(unitDir, EMBEDDED_MANIFEST_FILE), lines.join('\n'), 'utf-8')
  return entries.map(([name]) => name)
}
