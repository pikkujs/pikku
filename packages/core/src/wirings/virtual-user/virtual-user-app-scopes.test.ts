import assert from 'node:assert/strict'
import { describe, test } from 'node:test'
import {
  appScopeId,
  buildAppScopeDefinition,
  declaredApps,
} from './virtual-user-app-scopes.js'

const virtualUser = (id: string, app?: string) =>
  ({ id, name: id, roles: [], goals: [], tags: [], runnable: true, app }) as any

describe('declaredApps', () => {
  test('deduplicates and sorts the apps the virtual users name', () => {
    assert.deepEqual(
      declaredApps([
        virtualUser('a', 'staff'),
        virtualUser('b', 'portal'),
        virtualUser('c', 'staff'),
      ]),
      ['portal', 'staff']
    )
  })

  test('ignores virtual users that name no app', () => {
    assert.deepEqual(declaredApps([virtualUser('a'), virtualUser('b', '')]), [])
  })
})

describe('buildAppScopeDefinition', () => {
  test('renders one grantable child per app under the app root', () => {
    const definition = buildAppScopeDefinition([
      virtualUser('a', 'staff'),
      virtualUser('b', 'portal'),
    ])

    assert.equal(definition?.name, 'app')
    assert.deepEqual(Object.keys(definition?.scopes ?? {}).sort(), [
      'portal',
      'staff',
    ])
    assert.equal(appScopeId('staff'), 'app:staff')
  })

  test('is generated by pikku, not declared by the app', () => {
    const definition = buildAppScopeDefinition([virtualUser('a', 'staff')])
    assert.deepEqual(definition?.origin, { kind: 'generated' })
  })

  test('is null for a single-frontend product', () => {
    assert.equal(buildAppScopeDefinition([virtualUser('a')]), null)
  })
})
