import type { ScopeDefinitions } from '@pikku/core/scope'
import { flattenScopeDefinitions } from '@pikku/core/scope'

export interface SerializeScopesClientOptions {
  definitions: ScopeDefinitions
}

const quote = (value: string) => `'${value.replace(/'/g, "\\'")}'`

/**
 * Generates the browser-side scope client: the `ScopeId` union and a
 * `hasScopes` that decides whether held grants satisfy a requirement.
 *
 * The cascade is emitted inline rather than imported, so the file a frontend
 * bundles has no imports at all. `@pikku/core` is a server package — it pulls
 * AsyncLocalStorage and the wiring runtime behind it — so a UI reaching for
 * `@pikku/core/scope` to render a permission drags the server into the bundle.
 * `serialize-scopes-client.test.ts` checks this copy against core's over a
 * shared case table.
 */
export const serializeScopesClient = ({
  definitions,
}: SerializeScopesClientOptions) => {
  const flat = flattenScopeDefinitions(definitions)
  const ids = flat.map((s) => s.id)

  const hasChildren = (id: string) =>
    ids.some((other) => other.startsWith(`${id}:`))

  const requirable = [
    ...ids,
    ...ids.filter(hasChildren).map((id) => `${id}:*`),
  ].sort()

  const union =
    requirable.length > 0
      ? `\n${requirable.map((id) => `  | ${quote(id)}`).join('\n')}`
      : ' never'

  return `/**
 * This file was generated by the @pikku/cli
 */

/**
 * Every scope a function can require.
 *
 * A \`:*\` entry requires the scope and all of its descendants. A held grant of
 * \`admin:*\` satisfies any \`admin:...\` requirement.
 */
export type ScopeId =${union}

const SEPARATOR = ':'
const WILDCARD = '*'

const satisfyingGrants = (scope: string): string[] => {
  const segments = scope.split(SEPARATOR)
  const grants = [scope, \`\${scope}\${SEPARATOR}\${WILDCARD}\`]
  for (let i = 0; i < segments.length; i++) {
    grants.push([...segments.slice(0, i), WILDCARD].join(SEPARATOR))
  }
  for (let i = 1; i < segments.length; i++) {
    grants.push(segments.slice(0, i).join(SEPARATOR))
  }
  return grants
}

const holds = (held: ReadonlySet<string>, scope: string): boolean =>
  satisfyingGrants(scope).some((grant) => held.has(grant))

/**
 * Whether \`held\` satisfies every scope in \`required\`.
 *
 * Fails closed: absent grants satisfy nothing. An empty \`required\` is
 * satisfied by anything.
 */
export const hasScopes = (
  required: readonly string[] | undefined,
  held: Iterable<string> | undefined
): boolean => {
  if (!required || required.length === 0) {
    return true
  }
  const grants = new Set(held ?? [])
  return required.every((scope) => holds(grants, scope))
}
`
}
