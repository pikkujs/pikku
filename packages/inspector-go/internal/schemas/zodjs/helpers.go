package zodjs

import (
	_ "embed"
	"fmt"
	"path/filepath"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
)

//go:generate go run ./gen

// helpersJS is zodToTypeText and findZodTransform from @pikku/inspector,
// bundled to plain JavaScript by `go generate`. The TS engine runs the same
// two functions in-process, so both engines describe a Zod schema with one
// piece of code. TestHelpersAreCurrent fails when the inspector's sources
// have moved on without this file being regenerated.
//
//go:embed helpers.gen.js
var helpersJS string

// HelperSources are the inspector files helpers.gen.js is built from,
// relative to this package.
var HelperSources = []string{
	"../../../../inspector/src/utils/zod-to-type-text.ts",
	"../../../../inspector/src/utils/find-zod-transform.ts",
}

const helpersHeader = "// Code generated by go generate (./gen) from @pikku/inspector's zod-to-type-text.ts\n" +
	"// and find-zod-transform.ts. DO NOT EDIT.\n"

// BundleHelpers builds helpers.gen.js from HelperSources, resolved against
// dir (this package's directory).
func BundleHelpers(dir string) ([]byte, error) {
	var entry strings.Builder
	for _, src := range HelperSources {
		abs, err := filepath.Abs(filepath.Join(dir, src))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&entry, "export * from %q\n", filepath.ToSlash(abs))
	}
	res := api.Build(api.BuildOptions{
		Stdin:         &api.StdinOptions{Contents: entry.String(), ResolveDir: dir, Loader: api.LoaderJS, Sourcefile: "helpers-entry.js"},
		Bundle:        true,
		Format:        api.FormatESModule,
		Platform:      api.PlatformNeutral,
		Target:        api.ES2020,
		Charset:       api.CharsetUTF8,
		LogLevel:      api.LogLevelSilent,
		LegalComments: api.LegalCommentsNone,
	})
	if len(res.Errors) > 0 {
		return nil, fmt.Errorf("bundling the inspector's Zod helpers: %s", res.Errors[0].Text)
	}
	return append([]byte(helpersHeader), res.OutputFiles[0].Contents...), nil
}
