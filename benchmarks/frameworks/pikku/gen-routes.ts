import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PERMISSION_COUNT, routeTable } from '../shared/routes.js'

/** Writes src/routes.gen.ts: N explicit pikkuFunc + wireHTTP calls (the CLI reads wirings from source, so no runtime loop). */
export const generateRoutes = (n: number) => {
  const here = dirname(fileURLToPath(import.meta.url))
  const perms = Array.from(
    { length: PERMISSION_COUNT },
    (_, p) =>
      `const p${p} = pikkuAuth(async (_services, session) => hasPermission(session.permissions, 'p${p}'))`
  )
  const routes = routeTable(n).map(
    (r) => `export const r${r.index} = pikkuFunc({
  input: itemInput,
  func: async ({ kysely }, data) => {
    const row = await readItem(kysely, data.id)
    return { route: ${r.index}, id: row!.id, name: row!.name, value: row!.value }
  },
  permissions: { guard: ${r.permission} },
})
wireHTTP({ route: '${r.path}', method: 'post', func: r${r.index} })`
  )
  writeFileSync(
    join(here, 'src', 'routes.gen.ts'),
    `// generated by gen-routes.ts, do not edit
import { pikkuFunc } from '#pikku/function'
import { pikkuAuth } from '#pikku/auth'
import { wireHTTP } from '#pikku/http'
import { itemInput } from '../../shared/routes.js'
import { readItem } from '../../shared/db.js'
import { hasPermission } from '../../shared/auth-options.js'

${perms.join('\n')}

${routes.join('\n\n')}
`
  )
}

if (process.argv[2]) generateRoutes(Number(process.argv[2]))
