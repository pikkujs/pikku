import { rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { InspectorState } from '@pikku/inspector'
import type {
  ContributorSupport,
  EntryGenerationContext,
  EntryPlatformServices,
  ProviderAdapter,
} from '@pikku/deploy'
import { withDeployUnit } from '@pikku/deploy'
import { resolveTargetContributors } from '../contributors/resolve-contributors.js'
import { serializeContributors } from '../contributors/serialize-contributors.js'

export const PLATFORM_SERVICES_FILE = 'platform-services.gen.ts'

type OptedInState = Parameters<typeof resolveTargetContributors>[0]['state'] &
  Pick<InspectorState, 'optedInContributors'>

const hasDeployVariant = (state: OptedInState): boolean =>
  Object.values(state.optedInContributors ?? {}).some(({ contributors }) =>
    Object.values(contributors).some((variants) => variants.deploy)
  )

/**
 * What the provider-agnostic server entry holds when contributors run: nothing
 * (it builds no services of its own), with `process.env` as the bindings.
 */
export const genericServerEntrySupport = (
  ctx: EntryGenerationContext
): ContributorSupport => ({
  supported: ['env'],
  runtimeServices: [],
  runsServerLifecycle: true,
  widenPlatform: (platform) => withDeployUnit(platform, ctx.unit),
})

/**
 * Selects the contributors for one unit and writes the platform-services file
 * the provider's entry imports, or removes a stale one and returns undefined
 * when nothing is selected.
 *
 * The provider says what its runtime supports (`contributorSupport`); this is
 * the one place that turns it, the unit's platform and the project's opt-ins
 * into the file, so every adapter gets the same selection, ordering and errors.
 * A provider with no `contributorSupport` cannot run a contributor, so a
 * project that opted in to one with a deploy variant fails the build there
 * rather than shipping without it.
 */
export async function writeUnitPlatformServices(options: {
  provider: ProviderAdapter
  ctx: EntryGenerationContext
  state: OptedInState
  projectDir: string
  /**
   * True when the unit's entry is generated by the provider-agnostic server
   * entry generator, which supports platform services on its own terms
   * (`genericServerEntrySupport`) instead of the provider's.
   */
  genericServerEntry?: boolean
  /** Told about a contributor hook the target will not run (a warning, not an error). */
  warn?: (message: string) => void
}): Promise<EntryPlatformServices | undefined> {
  const { provider, ctx, state, projectDir } = options
  const file = join(ctx.unitDir, PLATFORM_SERVICES_FILE)
  const remove = () => rm(file, { force: true })

  const support = options.genericServerEntry
    ? genericServerEntrySupport(ctx)
    : provider.contributorSupport?.(ctx)
  if (!support) {
    if (hasDeployVariant(state)) {
      throw new Error(
        `The ${provider.name} deploy cannot run the contributors the project opted in to with wireAddon (unit '${ctx.unit.name}'): its entry builds no platform services. Remove them from wireAddon({ contributors }) or deploy with a provider that supports them.`
      )
    }
    await remove()
    return undefined
  }

  const base = ctx.contributorPlatform
  if (!base) {
    throw new Error(
      `No contributor platform was built for unit '${ctx.unit.name}'; the build pipeline sets it before the entry is generated.`
    )
  }
  const withRuntime = { ...base, runtimeServices: [...support.runtimeServices] }
  const platform = support.widenPlatform?.(withRuntime) ?? withRuntime

  const { ordered, ignoredStopHooks } = await resolveTargetContributors({
    state,
    rootDir: projectDir,
    target: 'deploy',
    platform,
    supported: support.supported,
    extra: support.framework,
    targetLabel: `The ${provider.name} deploy`,
    runsServerLifecycle: support.runsServerLifecycle === true,
    unitLabel: `unit '${ctx.unit.name}'`,
  })
  for (const name of ignoredStopHooks) {
    options.warn?.(
      `contributor '${name}' declares onServerStop, which unit '${ctx.unit.name}' (${provider.name}) never calls: it does not run the server lifecycle.`
    )
  }
  if (ordered.length === 0) {
    await remove()
    return undefined
  }

  await writeFile(
    file,
    serializeContributors({
      contributors: ordered,
      platform,
      specifier: ({ module }) => module.replace(/\\/g, '/'),
    }),
    'utf-8'
  )
  return { importPath: `./${PLATFORM_SERVICES_FILE.replace(/\.ts$/, '.js')}` }
}
