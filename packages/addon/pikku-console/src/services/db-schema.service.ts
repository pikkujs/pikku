import type { ColumnConstraints } from '@pikku/core/db'
import type { MetaService } from '@pikku/core/services'

export type Classification = 'public' | 'private' | 'pii' | 'secret'

export interface DbColumn {
  name: string
  type: string
  nullable: boolean
  isPrimaryKey: boolean
  classification: Classification
  foreignKey?: { table: string; column: string }
  enumType?: string
  description?: string
  /** What the declaration restricts the column to: bounds, lengths, a pattern, an enum. Form hints read these. */
  constraints?: ColumnConstraints
}

export interface DbTable {
  name: string
  columns: DbColumn[]
  /**
   * Who declared this table: `app` for the project's own migrations, otherwise
   * the source label `pikku db generate` gave the migration that created it
   * (`better-auth`, `pikku-runtime`, an addon's package name).
   *
   * Absent when the schema JSON predates provenance — a consumer that needs to
   * tell framework tables apart has to fall back rather than assume `app`.
   */
  source?: string
  /** Human prose naming where the table's SQL came from, for a tooltip. */
  origin?: string
}

export interface DbEnum {
  name: string
  schema: string
  values: string[]
}

export interface DbSchema {
  tables: DbTable[]
  enums: DbEnum[]
}

// ── Helpers ───────────────────────────────────────────────────────────────────

function classificationFor(security: string | undefined): Classification {
  if (
    security === 'public' ||
    security === 'private' ||
    security === 'pii' ||
    security === 'secret'
  )
    return security
  return 'private'
}

const CONSTRAINT_KEYS = [
  'min',
  'max',
  'minLength',
  'maxLength',
  'pattern',
  'enum',
] as const

/** The constraint fields of an annotation entry, or nothing when it declares none. */
function constraintsOf(
  ann: AnnotationEntry | undefined
): ColumnConstraints | undefined {
  if (!ann) return undefined
  const found: Record<string, unknown> = {}
  for (const key of CONSTRAINT_KEYS) {
    if (ann[key] !== undefined) found[key] = ann[key]
  }
  return Object.keys(found).length ? (found as ColumnConstraints) : undefined
}

function camelToSnake(s: string): string {
  return s.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`)
}

function bareTableName(name: string): string {
  const dot = name.indexOf('.')
  return dot >= 0 ? name.slice(dot + 1) : name
}

interface AnnotationEntry extends ColumnConstraints {
  /**
   * The privacy level, named as a column in `db/tables.ts` declares it. The
   * sidecar carries those fields as written, so this is the key that is there.
   */
  security?: 'public' | 'private' | 'pii' | 'secret'
  /**
   * What `security` was called before the rename. Sidecars generated by an older
   * CLI still carry it, and they are not regenerated until the project next runs
   * `db migrate`, so both spellings have to be read.
   *
   * Not to be confused with the entry's `classification`, which is the anonymize
   * strategy (`hash`, `fake:email`) under BOTH spellings and never the privacy
   * level.
   */
  visibility?: 'public' | 'private' | 'pii' | 'secret'
  description?: string
}

type AnnotationsJson = Record<string, Record<string, AnnotationEntry>>

async function loadAnnotations(
  metaService: MetaService
): Promise<Record<string, Record<string, AnnotationEntry>>> {
  const raw = await metaService.readFile('db/annotations.gen.json')
  if (!raw) return {}
  const data = JSON.parse(raw) as AnnotationsJson
  const result: Record<string, Record<string, AnnotationEntry>> = {}
  for (const [tableName, cols] of Object.entries(data)) {
    const key = camelToSnake(bareTableName(tableName))
    result[key] = {}
    for (const [col, entry] of Object.entries(cols)) {
      result[key][camelToSnake(col)] = entry
    }
  }
  return result
}

// ── Raw JSON shape (from pikku-db-schema.gen.json) ────────────────────────────

interface RawColumn {
  name: string
  type: string
  nullable: boolean
  isPrimaryKey: boolean
  foreignKey?: { table: string; column: string }
}

interface RawTable {
  name: string
  columns: RawColumn[]
  source?: string
  origin?: string
}

interface RawSchema {
  tables: RawTable[]
  enums: DbEnum[]
}

// ── Service ───────────────────────────────────────────────────────────────────

export class DbSchemaService {
  constructor(private readonly metaService: MetaService) {}

  async getSchema(): Promise<DbSchema | null> {
    const raw = await this.metaService.readFile('db/pikku-db-schema.gen.json')
    if (!raw) return null

    const parsed = JSON.parse(raw) as RawSchema
    const annotations = await loadAnnotations(this.metaService)

    const tables: DbTable[] = parsed.tables.map((t) => {
      const tableAnns = annotations[bareTableName(t.name)] ?? {}
      const table: DbTable = {
        name: t.name,
        columns: t.columns.map((c) => {
          const ann = tableAnns[c.name]
          const col: DbColumn = {
            name: c.name,
            type: c.type,
            nullable: c.nullable,
            isPrimaryKey: c.isPrimaryKey,
            classification: classificationFor(ann?.security ?? ann?.visibility),
          }
          if (ann?.description) col.description = ann.description
          const constraints = constraintsOf(ann)
          if (constraints) col.constraints = constraints
          if (c.foreignKey) col.foreignKey = c.foreignKey
          return col
        }),
      }
      if (t.source) table.source = t.source
      if (t.origin) table.origin = t.origin
      return table
    })

    return { tables, enums: parsed.enums }
  }
}
