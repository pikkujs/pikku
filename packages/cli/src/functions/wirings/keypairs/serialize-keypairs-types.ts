import type { KeyPairDefinitionsMeta } from '@pikku/core/keypair'

/**
 * The generated `#pikku/keypairs` file. It is always written, with an empty map
 * when nothing is declared, so `keys.sign` / `keys.open` have a map to be typed
 * against. It records names, purposes and algorithms only: never key material.
 */
export const serializeKeyPairsTypes = (meta: KeyPairDefinitionsMeta) => {
  const entries = Object.entries(meta).map(
    ([name, m]) =>
      `  ${JSON.stringify(name)}: { purpose: ${JSON.stringify(m.purpose)}; algorithm: ${JSON.stringify(m.algorithm)} }`
  )
  const map = entries.length === 0 ? '{}' : `{\n${entries.join('\n')}\n}`
  return `/**
 * Generated by Pikku. Do not edit.
 */
import type {
  SigningKeyName as CoreSigningKeyName,
  SealingKeyName as CoreSealingKeyName,
} from '@pikku/core/keypair'

export type KeyPairsMap = ${map}

/** Names of the signing key pairs: what \`keys.sign\` accepts. */
export type SigningKeyName = CoreSigningKeyName<KeyPairsMap>

/** Names of the sealing key pairs: what \`keys.open\` accepts. */
export type SealingKeyName = CoreSealingKeyName<KeyPairsMap>
`
}
