import assert from 'node:assert/strict'
import test from 'node:test'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { ErrorCode } from '@pikku/inspector'
import { generateSchemaTypes } from './db-codegen.js'
import type { ColumnInfo, DbIntrospector } from './db-introspector.js'
import {
  BETTER_AUTH_ANNOTATIONS,
  withBuiltinAnnotations,
} from './builtin-annotations.js'

const generated = (source: string, body: string) => ({
  [`0001-${source}.sql`]:
    `-- Generated by \`pikku db generate\` from ${source}.\n\n` + body + '\n',
})

function project(
  migrations: Record<string, string>,
  annotations?: Record<string, unknown>
) {
  const dir = mkdtempSync(join(tmpdir(), 'builtin-annotations-'))
  const migrationsDir = join(dir, 'db', 'sqlite')
  mkdirSync(migrationsDir, { recursive: true })
  for (const [name, sql] of Object.entries(migrations)) {
    writeFileSync(join(migrationsDir, name), sql, 'utf8')
  }
  if (annotations) {
    writeFileSync(
      join(dir, 'db', 'annotations.gen.json'),
      JSON.stringify(annotations),
      'utf8'
    )
  }
  return { dir, migrationsDir }
}

const AUTH = generated(
  'better-auth',
  'create table "user" ("id" text primary key, "email" text);'
)

test('Better Auth tables get the built-in annotations with no db/tables.ts at all', () => {
  const { migrationsDir } = project(AUTH)
  const merged = withBuiltinAnnotations({}, migrationsDir)
  assert.equal(merged.user?.email?.classification, 'pii')
  assert.equal(merged.user?.email?.format, 'email')
})

test('a project table that merely shares the name is left alone', () => {
  const { migrationsDir } = project({
    '0001-init.sql': 'create table "user" ("id" text primary key);',
  })
  assert.deepEqual(withBuiltinAnnotations({}, migrationsDir), {})
})

test('a project column replaces the built-in column outright', () => {
  const { migrationsDir } = project(AUTH)
  const merged = withBuiltinAnnotations(
    { user: { email: { classification: 'private' } } },
    migrationsDir
  )
  assert.deepEqual(merged.user?.email, { classification: 'private' })
})

test('the built-ins keep columns the project did not annotate', () => {
  const { migrationsDir } = project(
    generated(
      'better-auth',
      'create table "account" ("id" text primary key, "password" text, "access_token" text);'
    )
  )
  const merged = withBuiltinAnnotations(
    {
      account: { access_token: { classification: 'secret', form: 'wrapped' } },
    },
    migrationsDir
  )
  assert.equal(merged.account?.password?.form, 'hashed')
  assert.equal(merged.account?.access_token?.form, 'wrapped')
})

test('without a migrations directory nothing is added', () => {
  assert.deepEqual(withBuiltinAnnotations({}, undefined), {})
})

test('the runtime ciphertext columns are secret and plain, for the runtime tables only', () => {
  const runtime = project(
    generated(
      'pikku-runtime',
      'create table "secrets" ("key" text primary key, "ciphertext" text, "wrapped_dek" text);'
    )
  )
  const merged = withBuiltinAnnotations({}, runtime.migrationsDir)
  assert.equal(merged.secrets?.ciphertext?.classification, 'secret')
  assert.equal(merged.secrets?.ciphertext?.form, 'plain')
  assert.equal(merged.secrets?.wrapped_dek?.form, 'plain')

  const own = project({
    '0001-init.sql': 'create table "secrets" ("key" text primary key);',
  })
  assert.deepEqual(withBuiltinAnnotations({}, own.migrationsDir), {})
})

test('no built-in secret leaves its form unstated, and none is wrapped or sealed', () => {
  for (const [table, columns] of Object.entries(BETTER_AUTH_ANNOTATIONS)) {
    for (const [column, annotation] of Object.entries(columns)) {
      assert.ok(
        annotation.security !== 'secret' || annotation.form !== undefined,
        `${table}.${column} is secret with no form`
      )
      assert.ok(
        annotation.form !== 'wrapped' && annotation.form !== 'sealed',
        `${table}.${column} would be touched by the column encryption plugin`
      )
    }
  }
})

function introspector(table: string, columns: ColumnInfo[]): DbIntrospector {
  return {
    async listTables() {
      return [table]
    },
    async getColumns() {
      return columns
    },
    async getForeignKeys() {
      return []
    },
    async getAllColumns() {
      return new Map([[table, columns]])
    },
    async getAllForeignKeys() {
      return new Map()
    },
    async listEnums() {
      return []
    },
    async close() {},
  }
}

test('codegen brands the auth columns and raises no secret-form warning', async () => {
  const { dir, migrationsDir } = project(
    generated(
      'better-auth',
      'create table "account" ("id" text primary key, "password" text, "access_token" text, "email" text);'
    )
  )
  const col = (name: string): ColumnInfo => ({
    name,
    type: 'text',
    notNull: false,
    pk: false,
    defaultValue: null,
  })
  const result = await generateSchemaTypes(
    introspector('account', [col('password'), col('access_token')]),
    {
      outFile: join(dir, 'schema.gen.ts'),
      coercionFile: join(dir, 'coercion.gen.ts'),
      dialect: 'sqlite',
      rootDir: dir,
      migrationsDir,
    }
  )
  const schema = readFileSync(result.outFile, 'utf8')
  assert.match(schema, /password: ColumnType<Secret<HashedValue>/)
  assert.match(schema, /accessToken: ColumnType<Secret<string>/)
  assert.equal(
    result.warnings.filter(
      (w) => w.code === ErrorCode.DB_SECRET_COLUMN_STORED_PLAIN
    ).length,
    0,
    JSON.stringify(result.warnings)
  )
})
