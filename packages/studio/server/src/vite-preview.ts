function omIdPlugin(api) {
  const t = api.types
  return {
    pre() { this._omSeq = 0 },
    visitor: {
      JSXOpeningElement(path, state) {
        if (!state.filename) return
        const { name } = path.node.name
        if (typeof name !== 'string') return
        // Strip any query suffix (e.g. TanStack Start route code-splitting emits
        // virtual modules like \`index.tsx?tsr-split=component\`) so the om-id
        // value stays a clean source path.
        const rawFile = state.filename.split('?')[0]
        const file = rawFile.startsWith(cwd) ? rawFile.slice(cwd.length + 1) : rawFile
        // Prefer the real source location; fall back to a per-file sequence when
        // a prior transform (route splitting) regenerated the AST without loc.
        const omId = path.node.loc
          ? file + ':' + path.node.loc.start.line + ':' + path.node.loc.start.column
          : file + '#' + (this._omSeq++)
        path.node.attributes.push(
          t.jsxAttribute(t.jsxIdentifier('data-om-id'), t.stringLiteral(omId)),
          t.jsxAttribute(t.jsxIdentifier('data-om-component'), t.stringLiteral(name))
        )
        // Extract an i18n key for this element. Paraglide is the only shape:
        // {m.key()} / label={m['key']()} — the message-function name IS the key
        // (flat snake/double-underscore, e.g. app_shell__title).
        // Stamp a single best key as a bare string so the click bridge can post it.
        const i18nKeyOf = (expr) => {
          if (!expr) return null
          // m.key() / m['key']()  (Paraglide message namespace)
          if (expr.type === 'CallExpression') {
            const callee = expr.callee
            if (callee.type === 'MemberExpression' && callee.object.type === 'Identifier' && callee.object.name === 'm') {
              if (!callee.computed && callee.property.type === 'Identifier') return callee.property.name
              if (callee.computed && callee.property.type === 'StringLiteral') return callee.property.value
            }
          }
          // condition ? m.key() : fallback  or  fallback : m.key()
          if (expr.type === 'ConditionalExpression') {
            return i18nKeyOf(expr.consequent) || i18nKeyOf(expr.alternate)
          }
          // condition && m.key()  or  condition || m.key()
          if (expr.type === 'LogicalExpression') {
            return i18nKeyOf(expr.left) || i18nKeyOf(expr.right)
          }
          return null
        }
        const i18nByProp = {}
        for (const attr of path.node.attributes) {
          if (attr.type !== 'JSXAttribute' || !attr.name || attr.name.type !== 'JSXIdentifier') continue
          const v = attr.value
          if (!v || v.type !== 'JSXExpressionContainer') continue
          const k = i18nKeyOf(v.expression)
          if (k) i18nByProp[attr.name.name] = k
        }
        const jsxEl = path.parentPath.node
        let childrenKey = null
        for (const child of ((jsxEl && jsxEl.children) || [])) {
          if (child.type !== 'JSXExpressionContainer') continue
          const k = i18nKeyOf(child.expression)
          if (k) { childrenKey = k; break }
        }
        const bestKey = childrenKey || i18nByProp.label || i18nByProp.placeholder ||
          i18nByProp.title || i18nByProp.description || Object.values(i18nByProp)[0]
        if (bestKey) {
          path.node.attributes.push(t.jsxAttribute(t.jsxIdentifier('data-om-i18n'), t.stringLiteral(bestKey)))
        }
      },
      // Wrap every m.key() call so its rendered string is registered in window.__omI18nRegistry.
      // This lets the click handler find the key even when m.key() is passed as a prop
      // to a custom component that doesn't forward data-om-i18n to the DOM.
      CallExpression(path) {
        const callee = path.node.callee
        if (callee.type !== 'MemberExpression') return
        if (callee.object.type !== 'Identifier' || callee.object.name !== 'm') return
        const key = callee.computed
          ? (callee.property.type === 'StringLiteral' ? callee.property.value : null)
          : (callee.property.type === 'Identifier' ? callee.property.name : null)
        if (!key) return
        const orig = t.cloneNode(path.node, true)
        // SSR-safe: ternary checks globalThis at call time; on the server
        // globalThis.__omI18nReg is undefined so m.key() is called directly.
        path.replaceWith(
          t.conditionalExpression(
            t.memberExpression(t.identifier('globalThis'), t.identifier('__omI18nReg')),
            t.callExpression(
              t.memberExpression(t.identifier('globalThis'), t.identifier('__omI18nReg')),
              [t.stringLiteral(key), t.cloneNode(orig, true)]
            ),
            orig
          )
        )
        path.skip()
      }
    }
  }
}

