import { PikkuCLIConfigError } from './pikku-cli-config-error.js'

/**
 * A bucket is one directory under the content root (`LocalContent.safePath`
 * resolves bucket and key and refuses a climb out of it, and a private bucket
 * may not start with `_public`). Here it is also a TypeScript string literal,
 * so it is one plain path segment.
 */
const BUCKET_NAME = /^[A-Za-z0-9_][A-Za-z0-9._-]*$/
const RESERVED_BUCKETS = new Set(['_public'])

const isRecord = (value: unknown): value is Record<string, unknown> =>
  value !== null && typeof value === 'object' && !Array.isArray(value)

const checkBuckets = (
  value: unknown,
  where: string,
  file: string
): string[] => {
  if (!Array.isArray(value) || value.length === 0) {
    throw new PikkuCLIConfigError(
      `${where} in ${file} must be a non-empty list of bucket names. Leave the content block out to give no content access.`
    )
  }
  const seen = new Set<string>()
  for (const name of value) {
    if (
      typeof name !== 'string' ||
      !BUCKET_NAME.test(name) ||
      RESERVED_BUCKETS.has(name)
    ) {
      throw new PikkuCLIConfigError(
        `${where} in ${file} has an invalid bucket name ${JSON.stringify(name)}: use one path segment of letters, digits, '.', '_' or '-' (not '_public').`
      )
    }
    if (seen.has(name)) {
      throw new PikkuCLIConfigError(
        `${where} in ${file} lists bucket '${name}' twice.`
      )
    }
    seen.add(name)
  }
  return value as string[]
}

/**
 * Content is closed by default. The root `content.buckets` is every bucket that
 * exists; a backend may use only the ones it lists in
 * `backends.<name>.content.buckets`, and none when it lists none.
 * Key names are checked by `assertKnownConfigKeys`, which runs first.
 */
export const assertContentConfig = (
  config: Record<string, unknown>,
  file: string
): void => {
  const root = config.content
  let declared: Set<string> | undefined
  if (root !== undefined) {
    if (!isRecord(root)) {
      throw new PikkuCLIConfigError(`content in ${file} must be an object.`)
    }
    declared = new Set(checkBuckets(root.buckets, 'content.buckets', file))
  }
  const backends = config.backends
  if (!isRecord(backends)) return
  for (const [name, entry] of Object.entries(backends)) {
    const content = isRecord(entry) ? entry.content : undefined
    if (content === undefined) continue
    if (!isRecord(content)) {
      throw new PikkuCLIConfigError(
        `backends.${name}.content in ${file} must be an object.`
      )
    }
    const buckets = checkBuckets(
      content.buckets,
      `backends.${name}.content.buckets`,
      file
    )
    if (!declared) {
      throw new PikkuCLIConfigError(
        `backends.${name}.content in ${file} uses content but the project declares no \`content.buckets\`. Add the root block: "content": { "buckets": [${buckets.map((b) => JSON.stringify(b)).join(', ')}] }.`
      )
    }
    for (const bucket of buckets) {
      if (!declared.has(bucket)) {
        throw new PikkuCLIConfigError(
          `backends.${name}.content.buckets in ${file} names '${bucket}', which is not in the root content.buckets (${[...declared].join(', ')}). Declare it there first.`
        )
      }
    }
  }
}

/** The buckets a backend may use; empty when it has no `content`. */
export const backendBuckets = (
  config: { backends?: Record<string, { content?: { buckets?: string[] } }> },
  backend: string
): string[] => config.backends?.[backend]?.content?.buckets ?? []

/** The file `pikku all` writes per backend, typing the buckets its code may use. */
export const renderContentBucketsFile = (buckets: string[]): string => {
  const union =
    buckets.length === 0
      ? 'never'
      : buckets.map((b) => JSON.stringify(b)).join(' | ')
  return `/**
 * The content buckets this backend may use, from backends.<name>.content.buckets
 * in pikku.config.json. Generated by \`pikku all\`; do not edit.
 * Type the service with it: \`content: ContentService<ContentBucket>\`.
 */
export type ContentBucket = ${union}

export const contentBuckets = ${JSON.stringify(buckets)} as const satisfies readonly ContentBucket[]
`
}
