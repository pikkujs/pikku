/**
 * `pikku bootstrap` at the root of a workspace, from a clean checkout. It is what
 * runs before `pikku db migrate`, which imports the main package's own source, so
 * that package's `#pikku` imports have to load afterwards.
 *
 *   1. bootstrap at the root generates in the addon and in the main package
 *   2. the main package's services load, through its own `#pikku` imports
 */
import { spawnSync } from 'node:child_process'
import { existsSync, rmSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(here, '../..')
const PIKKU = join(repoRoot, 'packages/cli/dist/bin/pikku.js')
const TSX = join(repoRoot, 'node_modules/.bin/tsx')
const fail = (message) => {
  console.error(`✗ ${message}`)
  process.exit(1)
}

for (const dir of ['.', 'packages/tools', 'packages/app']) {
  rmSync(join(here, dir, '.pikku'), { recursive: true, force: true })
}
const run = spawnSync('node', [PIKKU, 'bootstrap'], {
  cwd: here,
  encoding: 'utf8',
})
if (run.status !== 0) {
  console.error(run.stdout + run.stderr)
  fail('pikku bootstrap failed at the root')
}

for (const pkg of ['tools', 'app']) {
  if (!existsSync(join(here, 'packages', pkg, '.pikku'))) {
    fail(`packages/${pkg} was not generated by pikku bootstrap`)
  }
}
console.log('✓ bootstrap generated the addon and the main package')

const load = spawnSync(TSX, ['packages/app/src/services.ts'], {
  cwd: here,
  encoding: 'utf8',
})
if (load.status !== 0) {
  console.error(load.stdout + load.stderr)
  fail("the main package's services do not load after pikku bootstrap")
}
console.log("✓ the main package's services load")
