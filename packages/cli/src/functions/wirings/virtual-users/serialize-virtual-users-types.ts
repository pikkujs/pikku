import type { VirtualUserDefinitions } from '@pikku/core/virtual-user'
import { tsLiteral } from '../../../utils/ts-literal.js'

export interface SerializeVirtualUsersOptions {
  definitions: VirtualUserDefinitions
  /** Relative import path to the generated roles file. */
  rolesImportPath: string
  /** Keys of `environments` in pikku.config.json. */
  environmentNames: string[]
}

/**
 * Generates the `VirtualUserId` union and a `defineVirtualUsers` whose `roles` are
 * checked against the declared system roles.
 *
 * The wrapper is why this is generated rather than re-exported: `roles` typed
 * as `string[]` would let a virtual user name a role nobody declared, and the
 * failure — a scatter of 403s in a run days later — looks nothing like the
 * mistake. Typed as `SystemRoleName[]`, it is a red squiggle in the editor.
 */
export const serializeVirtualUsersTypes = ({
  rolesImportPath,
  environmentNames,
}: SerializeVirtualUsersOptions) => {
  const environmentUnion =
    environmentNames.length > 0
      ? `\n${[...environmentNames]
          .sort()
          .map((name) => `  | ${tsLiteral(name)}`)
          .join('\n')}`
      : ' never'

  return `/**
 * This file was generated by the @pikku/cli
 */
import { defineVirtualUsers as defineVirtualUsersCore } from '@pikku/core/virtual-user'
import type { VirtualUserMeta, VirtualUsersMeta } from '@pikku/core/virtual-user'
import type { CoreVirtualUser } from '@pikku/core/virtual-user'
import type { SystemRoleName } from '${rolesImportPath}'
import definitions from './pikku-virtual-users-meta.gen.json' with { type: 'json' }

/** Every environment configured in pikku.config.json. */
type EnvironmentName =${environmentUnion}

/**
 * A virtual user whose roles are checked against \`defineSystemRole\` and whose
 * environments are checked against the config.
 *
 * Omitting \`environments\` means every environment except the ones flagged
 * \`production: true\`. Naming a production one additionally requires
 * \`disposition: 'accountable'\`, which the type cannot express and \`pikku\`
 * refuses at build time.
 */
type TypedVirtualUser = Omit<CoreVirtualUser, 'roles' | 'environments'> & {
  roles?: SystemRoleName[]
  environments?: EnvironmentName[]
}

/**
 * Declare the people who use this application.
 */
export const defineVirtualUsers = (virtualUsers: Record<string, TypedVirtualUser>): void =>
  defineVirtualUsersCore(virtualUsers)

/** Declared virtual users, keyed by id. Read by the console and \`pikku virtual-user\`. */
export const VIRTUAL_USERS: VirtualUsersMeta = definitions as unknown as VirtualUsersMeta

export const VIRTUAL_USER_LIST: VirtualUserMeta[] = Object.values(VIRTUAL_USERS)
`
}
