import { describe, test } from 'node:test'
import assert from 'node:assert'
import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, realpathSync, symlinkSync } from 'node:fs'
import { mkdtemp, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { git } from '@pikku/cli/addon-support'
import { mergeChangeset } from './changeset-merge.js'

const ID = ['-c', 'user.email=t@example.com', '-c', 'user.name=t']

const pkg = (deps: string[], devDeps: string[]) =>
  [
    '{',
    '  "name": "lockheal",',
    '  "dependencies": {',
    deps.map((d) => `    "${d}": "file:./pkgs/${d}"`).join(',\n'),
    '  },',
    '  "private": true,',
    '  "version": "1.0.0",',
    '  "description": "two sides, two dependencies",',
    '  "devDependencies": {',
    devDeps.map((d) => `    "${d}": "file:./pkgs/${d}"`).join(',\n'),
    '  }',
    '}',
    '',
  ].join('\n')

const bunInstall = (dir: string) => {
  const r = spawnSync('bun', ['install'], { cwd: dir, encoding: 'utf8' })
  assert.strictEqual(r.status, 0, r.stderr)
}

/** main and changeset/deps each add a local dependency: package.json merges, bun.lock conflicts. */
const diverged = async () => {
  const dir = realpathSync(await mkdtemp(join(tmpdir(), 'lockheal-')))
  for (const name of ['a0', 'b0', 'x1', 'x2']) {
    mkdirSync(join(dir, 'pkgs', name), { recursive: true })
    await writeFile(
      join(dir, 'pkgs', name, 'package.json'),
      JSON.stringify({ name, version: '1.0.0' })
    )
  }
  await writeFile(join(dir, '.gitignore'), 'node_modules/\n')
  await writeFile(join(dir, 'package.json'), pkg(['a0'], ['b0']))
  bunInstall(dir)
  await git(['init', '-q', '-b', 'main'], dir)
  await git(['add', '.'], dir)
  await git([...ID, 'commit', '-q', '-m', 'init'], dir)
  await git(['switch', '-q', '-c', 'changeset/deps'], dir)
  await writeFile(join(dir, 'package.json'), pkg(['a0', 'x1'], ['b0']))
  bunInstall(dir)
  await git(['add', '.'], dir)
  await git([...ID, 'commit', '-q', '-m', '#1 x1'], dir)
  await git(['switch', '-q', 'main'], dir)
  await writeFile(join(dir, 'package.json'), pkg(['a0'], ['b0', 'x2']))
  bunInstall(dir)
  await git(['add', '.'], dir)
  await git([...ID, 'commit', '-q', '-m', 'x2'], dir)
  await git(['config', 'user.email', 't@example.com'], dir)
  await git(['config', 'user.name', 't'], dir)
  return dir
}

const merge = async (dir: string) => {
  const cwd = process.cwd()
  process.chdir(dir)
  try {
    return await mergeChangeset(
      {
        group: { groupId: 'g1', title: 'Add x1' } as any,
        branch: 'changeset/deps',
      },
      undefined
    )
  } finally {
    process.chdir(cwd)
  }
}

describe('a changeset whose only conflict is bun.lock', () => {
  test('is merged with the lockfile regenerated by bun install', async () => {
    const dir = await diverged()
    const outcome = await merge(dir)
    assert.strictEqual(outcome.kind, 'merged')
    const lock = readFileSync(join(dir, 'bun.lock'), 'utf8')
    assert.match(lock, /"x1"/)
    assert.match(lock, /"x2"/)
    assert.doesNotMatch(lock, /<<<<<<<|>>>>>>>/)
    assert.strictEqual((await git(['status', '--porcelain'], dir)).trim(), '')
    assert.match(await git(['log', '-1', '--format=%B'], dir), /Changeset: g1/)
    assert.strictEqual(
      (await git(['rev-list', '--parents', '-n1', 'HEAD'], dir))
        .trim()
        .split(' ').length,
      3
    )
  })

  test('PIKKU_CHANGES_LOCK_HEAL=off keeps it a conflict', async () => {
    const dir = await diverged()
    process.env.PIKKU_CHANGES_LOCK_HEAL = 'off'
    try {
      const outcome = await merge(dir)
      assert.strictEqual(outcome.kind, 'conflict')
      if (outcome.kind === 'conflict')
        assert.deepStrictEqual(outcome.files, ['bun.lock'])
    } finally {
      delete process.env.PIKKU_CHANGES_LOCK_HEAL
    }
  })

  test('a failed bun install aborts the merge and says why', async () => {
    const dir = await diverged()
    const bin = join(dir, '.nobun')
    mkdirSync(bin)
    const gitPath = spawnSync('which', ['git'], {
      encoding: 'utf8',
    }).stdout.trim()
    symlinkSync(gitPath, join(bin, 'git'))
    const path = process.env.PATH
    process.env.PATH = bin
    try {
      await assert.rejects(merge(dir), /bun install[\s\S]*merge was aborted/)
    } finally {
      process.env.PATH = path
    }
    assert.ok(
      !(await git(['status', '--porcelain', '--', 'bun.lock'], dir)).trim()
    )
    await assert.rejects(
      git(['rev-parse', '--verify', '-q', 'MERGE_HEAD'], dir)
    )
  })
})
